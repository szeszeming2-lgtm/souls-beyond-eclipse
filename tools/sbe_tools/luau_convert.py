"""Builds the Roblox GameData modules from shared-data JSON.

Each data file becomes one ModuleScript:
    shared-data/items/weapons.json  ->  GameData/Items/Weapons.luau
plus GameData/init.luau, an index that requires all of them.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from pathlib import Path

from .catalog import REPO_ROOT, DataFile
from .luau_writer import FREEZE, INDENT, to_luau

GENERATED_MARKER = "AUTO-GENERATED by tools/convert_to_luau.py"
DEFAULT_OUTPUT = REPO_ROOT / "roblox-game" / "src" / "shared" / "GameData"


class ConvertError(Exception):
    pass


def pascal(name: str) -> str:
    parts = [p for p in name.replace("-", "_").split("_") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def module_parts(rel: str) -> tuple[str, ...]:
    """'items/weapons.json' -> ('Items', 'Weapons')."""
    pieces = rel.removesuffix(".json").split("/")
    return tuple(pascal(p) for p in pieces)


def _header(lines: list[str]) -> str:
    return "\n".join(["--!strict", f"-- {GENERATED_MARKER}. DO NOT EDIT BY HAND."] + [f"-- {line}" for line in lines]) + "\n"


def render_module(data_file: DataFile) -> str:
    payload = {k: v for k, v in data_file.data.items() if k != "$schema"}
    digest = hashlib.sha256(data_file.path.read_bytes()).hexdigest()[:16]
    header = _header(
        [
            f"Source: shared-data/{data_file.rel} (sha256 {digest})",
            "Change the JSON file, then run: python3 tools/convert_to_luau.py",
        ]
    )
    body = to_luau(payload, 0, data_file.rel)
    return f"{header}\nlocal {FREEZE} = table.freeze\n\nreturn {body}\n"


def render_index(modules: dict[tuple[str, ...], DataFile]) -> str:
    tree: dict = {}
    for parts in modules:
        node = tree
        for folder in parts[:-1]:
            existing = node.setdefault(folder, {})
            if not isinstance(existing, dict):
                raise ConvertError(f"'{folder}' is both a data file and a folder name")
            node = existing
        if parts[-1] in node:
            raise ConvertError(f"two data files both become the module {'/'.join(parts)}")
        node[parts[-1]] = parts

    def emit(node: dict, depth: int) -> str:
        pad = INDENT * (depth + 1)
        lines = []
        for name in sorted(node):
            value = node[name]
            if isinstance(value, dict):
                lines.append(f"{pad}{name} = {emit(value, depth + 1)},")
            else:
                lines.append(f"{pad}{name} = require(script.{'.'.join(value)}),")
        return f"{FREEZE}({{\n" + "\n".join(lines) + f"\n{INDENT * depth}}})"

    combined = hashlib.sha256()
    for parts in sorted(modules):
        combined.update(modules[parts].path.read_bytes())
    header = _header(
        [
            "Index of every shared-data module.",
            "Use: local GameData = require(ReplicatedStorage.Shared.GameData)",
            "Arrays in these modules count from 1, unlike the JSON files (which count from 0).",
        ]
    )
    meta = f'{INDENT}_meta = {FREEZE}({{ generator = "tools/convert_to_luau.py", source_digest = "{combined.hexdigest()[:16]}" }}),'
    tree_text = emit(tree, 0)
    body = tree_text[: -len("\n})")] + f"\n{meta}\n}})"
    return f"{header}\nlocal {FREEZE} = table.freeze\n\nreturn {body}\n"


@dataclass
class Plan:
    expected: dict[Path, str] = field(default_factory=dict)  # absolute path -> content
    stale: list[Path] = field(default_factory=list)  # generated files that should be deleted
    foreign: list[Path] = field(default_factory=list)  # hand-written files in the output folder
    changed: list[Path] = field(default_factory=list)  # missing or different
    output_dir: Path = DEFAULT_OUTPUT


def plan(files: list[DataFile], output_dir: Path = DEFAULT_OUTPUT) -> Plan:
    result = Plan(output_dir=output_dir)
    modules: dict[tuple[str, ...], DataFile] = {}
    for data_file in files:
        parts = module_parts(data_file.rel)
        if parts in modules:
            raise ConvertError(f"{data_file.rel} and {modules[parts].rel} both become {'/'.join(parts)}.luau")
        modules[parts] = data_file
        result.expected[output_dir.joinpath(*parts[:-1], parts[-1] + ".luau")] = render_module(data_file)
    result.expected[output_dir / "init.luau"] = render_index(modules)

    for path, content in result.expected.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            result.changed.append(path)
    if output_dir.exists():
        for path in sorted(output_dir.rglob("*")):
            if path.is_dir() or path in result.expected or path.name == ".DS_Store":
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                text = ""
            (result.stale if GENERATED_MARKER in text else result.foreign).append(path)
    return result


def apply(result: Plan) -> None:
    """Write changed files and delete stale generated ones. Never deletes hand-written files."""
    if result.foreign:
        names = ", ".join(str(p.relative_to(result.output_dir)) for p in result.foreign)
        raise ConvertError(f"the generated folder contains files the converter did not make: {names}. Move them elsewhere.")
    for path in result.changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(result.expected[path], encoding="utf-8")
    for path in result.stale:
        path.unlink()
    for folder in sorted((p for p in result.output_dir.rglob("*") if p.is_dir()), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
